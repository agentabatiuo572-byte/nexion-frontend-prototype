import { writeFileSync } from "node:fs";
import rewritePattern from "regexpu-core";

// Commit the expanded patterns so older Android engines never parse \p{...}.
const options = { unicodePropertyEscapes: "transform", unicodeFlag: "transform" };
const holder = rewritePattern("^[\\p{L}\\p{M} .'-]+$", "u", options);
const han = rewritePattern("\\p{Script=Han}", "u", options);
// Keep Unicode escapes split at the source level: the i18n gate decodes \uXXXX
// in .ts files before scanning for hard-coded UI copy.
const legacyPatternString = (pattern) => JSON.stringify(pattern).replace(/\\\\/g, "\\x5c");
writeFileSync(new URL("../src/lib/native-unicode-regex.ts", import.meta.url),
  `// Generated by scripts/generate-native-unicode-regex.mjs; do not edit by hand.\n` +
  `export const BANK_HOLDER_NAME_RE = new RegExp(${legacyPatternString(holder)});\n` +
  `export const HAN_SCRIPT_RE = new RegExp(${legacyPatternString(han)});\n`);
