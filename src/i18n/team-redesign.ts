export function teamRedesignCopy(locale: string) {
  const language = locale.toLowerCase().split(/[-_]/)[0];
  return COPY[language as keyof typeof COPY] ?? COPY.en;
}

export function referralSettlementStatus(locale: string, bucket: 'withdrawable' | 'pending_review' | 'bonus_locked') {
  const labels = {
    zh: { withdrawable: '已入账 · 可用', pending_review: '已入账 · 处理中', bonus_locked: '已入账 · 待释放' },
    en: { withdrawable: 'Credited · Available', pending_review: 'Credited · Processing', bonus_locked: 'Credited · Pending release' },
    vi: { withdrawable: 'Đã ghi nhận · Khả dụng', pending_review: 'Đã ghi nhận · Đang xử lý', bonus_locked: 'Đã ghi nhận · Chờ mở khóa' },
  };
  return (labels[locale.toLowerCase().split(/[-_]/)[0] as keyof typeof labels] ?? labels.en)[bucket];
}
